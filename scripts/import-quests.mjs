// Builds supabase/seed-data/dungeon_quests.sql from the newest Efficient Games
// build. Run: node scripts/import-quests.mjs
// Then apply: npx supabase db query --remote -f supabase/seed-data/dungeon_quests.sql
//
// Data from Efficient Games (https://efficient.games), licensed under CC BY 4.0.
// Changed: reduced to dungeon quests and their prerequisites.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } from "../src/config.js";

const REPO = "https://raw.githubusercontent.com/JIVESCORP/eg-link-output-wowf/main/data";
const PRODUCT = "wowf";
const DUNGEON_QUEST_INFO = 81;
const OUT = new URL("../supabase/seed-data/dungeon_quests.sql", import.meta.url);

// raceMask bits per side, confirmed against Blizzard's quest data
// (92457 Starving Arcane is Alliance, 96986 The Grave Knight is Horde).
const ALLIANCE_MASK = BigInt("0x55155555b1354c4d");
const HORDE_MASK = BigInt("0xaa2aaaaa4e0ab3b2");
const MAX_CHAIN_DEPTH = 10;

// Faction corrections for quests the game data marks open to every race but
// that published guides give to one faction. Each entry names its source.
const FIXES = JSON.parse(await readFile(new URL("./quest-faction-fixes.json", import.meta.url), "utf8")).quests;
// Breadcrumbs whose follow-up the game data does not name.
const BREADCRUMBS = JSON.parse(await readFile(new URL("./quest-breadcrumbs.json", import.meta.url), "utf8")).quests;

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.json();
}

function factionOf(raceMask) {
  if (!raceMask) return null;
  const mask = BigInt(`0x${raceMask}`);
  if (mask === BigInt("0xffffffffffffffff")) return null;
  if ((mask & ~ALLIANCE_MASK) === 0n) return "ALLIANCE";
  if ((mask & ~HORDE_MASK) === 0n) return "HORDE";
  return null;
}

function shareableOf(votes) {
  if (!votes) return null;
  const yes = votes.true ?? 0;
  const no = votes.false ?? 0;
  if (yes === no) return null;
  return yes > no;
}

const sql = (v) => (v == null ? "null" : typeof v === "string" ? `'${v.replaceAll("'", "''")}'` : String(v));

const index = await getJson(`${REPO}/index.json`);
const builds = Object.keys(index.products[PRODUCT]).sort((a, b) =>
  a.split(".").map(Number).reduce((r, n, i) => r || n - b.split(".").map(Number)[i], 0)
);
const build = builds.at(-1);
console.log(`Efficient Games build ${build}`);

const [{ quests }, scan, npcs, dungeonRows] = await Promise.all([
  getJson(`${REPO}/${PRODUCT}/${build}/quests.enUS.json`),
  getJson(`${REPO}/${PRODUCT}/${build}/quest_scan.json`),
  getJson(`${REPO}/${PRODUCT}/${build}/npcs.json`),
  // Which areas are dungeons comes from our own dungeons table.
  fetch(`${SUPABASE_URL}/rest/v1/dungeons?select=name,area_id`, {
    headers: { apikey: SUPABASE_PUBLISHABLE_KEY },
  }).then((r) => r.json()),
]);

const areas = new Set(dungeonRows.map((d) => d.area_id).filter(Boolean));

// Who hands out each quest, where players saw it.
const givers = {};
for (const kind of ["npcs", "objects"]) {
  for (const giver of Object.values(npcs[kind] ?? {})) {
    for (const questId of Object.keys(giver.offers ?? {})) (givers[questId] ??= new Set()).add(giver.name);
  }
}

// The server's chain links: a quest whose nextQuestId is X comes before X.
const before = {};
for (const [id, q] of Object.entries(quests)) {
  if (q.nextQuestId) (before[q.nextQuestId] ??= new Set()).add(Number(id));
}

// Dungeon quests: typed Dungeon, open on the server, filed under a dungeon area.
const dungeonQuests = Object.entries(quests).filter(
  ([id, q]) => q.questInfoId === DUNGEON_QUEST_INFO && scan.described?.[id] && areas.has(q.zoneAreaId),
);

const prereqs = new Map(); // "quest|requires" -> row
function walk(questId, depth) {
  if (depth > MAX_CHAIN_DEPTH) return;
  for (const prev of before[questId] ?? []) {
    const key = `${questId}|${prev}`;
    if (prereqs.has(key)) continue;
    prereqs.set(key, { quest_id: Number(questId), requires_quest_id: prev, requires_title: quests[prev]?.title ?? null });
    walk(prev, depth + 1);
  }
}
for (const [id] of dungeonQuests) walk(Number(id), 0);

// Forward links: from each dungeon quest along what comes next, so a page can
// tell when a later step is done.
const nextOf = (id) => BREADCRUMBS[id]?.leadsTo ?? quests[id]?.nextQuestId ?? null;
const forward = new Map();
for (const [id] of dungeonQuests) {
  let at = Number(id);
  for (let depth = 0; depth < MAX_CHAIN_DEPTH; depth++) {
    const next = nextOf(at);
    if (!next || forward.has(at)) break;
    forward.set(at, next);
    at = next;
  }
}

const lines = [
  "-- Generated by scripts/import-quests.mjs. Do not edit by hand.",
  `-- Data from Efficient Games (https://efficient.games), build ${build}, licensed under CC BY 4.0.`,
  "-- Changed: reduced to dungeon quests and their prerequisites.",
  "begin;",
  "delete from public.quest_next;",
  "delete from public.quest_prereqs;",
  "delete from public.dungeon_quests;",
];

const questValues = dungeonQuests.map(([id, q]) =>
  `(${id}, ${q.zoneAreaId}, ${sql(q.title)}, ${sql(q.level ?? null)}, ${sql(q.minLevel ?? null)}, ` +
  `${sql(FIXES[id]?.faction ?? factionOf(q.raceMask))}, ${sql(shareableOf(scan.pushable?.[id]))}, ` +
  `${sql(givers[id] ? [...givers[id]].join(", ") : null)}, ${sql(build)})`
);
lines.push(
  "insert into public.dungeon_quests (quest_id, area_id, title, level, min_level, faction, shareable, giver, source_build) values",
  questValues.join(",\n") + ";",
);

if (prereqs.size) {
  const prereqValues = [...prereqs.values()].map((p) =>
    `(${p.quest_id}, ${p.requires_quest_id}, ${sql(p.requires_title)})`
  );
  lines.push(
    "insert into public.quest_prereqs (quest_id, requires_quest_id, requires_title) values",
    prereqValues.join(",\n") + ";",
  );
}
if (forward.size) {
  lines.push(
    "insert into public.quest_next (quest_id, next_quest_id) values",
    [...forward].map(([q, n]) => `(${q}, ${n})`).join(",\n") + ";",
  );
}
lines.push("commit;", "");

await mkdir(new URL("../supabase/seed-data/", import.meta.url), { recursive: true });
await writeFile(OUT, lines.join("\n"));

const perArea = {};
for (const [, q] of dungeonQuests) perArea[q.zoneAreaId] = (perArea[q.zoneAreaId] ?? 0) + 1;
const fixed = dungeonQuests.filter(([id]) => FIXES[id]).length;
console.log(`${fixed} faction corrections applied from scripts/quest-faction-fixes.json.`);
console.log(`${Object.keys(BREADCRUMBS).length} breadcrumbs from scripts/quest-breadcrumbs.json, ${forward.size} forward links.`);
console.log(`${dungeonQuests.length} dungeon quests in ${Object.keys(perArea).length} areas, ${prereqs.size} chain links.`);
console.log(`Wrote ${OUT.pathname}`);
